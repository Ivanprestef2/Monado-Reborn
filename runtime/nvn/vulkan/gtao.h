// [XCDE] GitHub #178 / #125: native per-frame physical-resolution GTAO replacing XCDE's temporal SSAO
// (shd_post.wishp SLCT 85 raymarch -> SLCT 86 bilateral blur H/V -> SLCT 87 temporal resolve -> SLCT 88 composite).
// Runs in the game's own AO slots (before fog, bloom, transparents, HUD, and FSR/DLSS), keeps its exact gTEtc
// material mask (skipping sky/emissives and softening character AO), uses purely spatial IGN (zero Halton-jitter
// silhouette shimmer and zero temporal ghosting trails), and runs at true physical resolution at any aspect ratio.
// Toggleable with XCDE_GTAO=0 (reverts to the game's original TSSAO).
#pragma once

// Pass 1 (SLCT 85, hashes 8ba81f6c23a705c7 / 5def0012e6637971): per-frame Horizon-Based GTAO (3 slices x 4 steps).
static const char monado_gtao_main_glsl[] =
    "#version 460\n"
    "layout(std140, set=1, binding=3) uniform CB3 { uvec4 cb3[16]; };\n"
    "layout(std140, set=1, binding=18) uniform RScale { vec4 rscale[129]; };\n"
    "layout(set=1, binding=32) uniform sampler2D t0;\n"  // gTDepth (signed linear view-Z)
    "layout(set=1, binding=33) uniform sampler2D t1;\n"  // gTNom (view-space normal)
    "layout(location=0) out vec4 c0;\n"
    "layout(location=1) out vec4 c1;\n"
    "layout(location=2) out vec4 c2;\n"
    "vec3 gtao_vpos(vec2 uv, float z, vec2 c2uv_s, vec2 c2uv_o, vec2 c2s_s, vec2 c2s_o, vec2 s2v) {\n"
    " vec2 g = (uv - c2uv_o) / c2uv_s;\n"
    " vec2 s = g * c2s_s + c2s_o;\n"
    " return vec3(z * s.x * s2v.x, -z * s.y * s2v.y, -z);\n"
    "}\n"
    "void main() {\n"
    " vec2 c2uv_s = uintBitsToFloat(cb3[2].xy), c2uv_o = uintBitsToFloat(cb3[2].zw);\n"
    " vec2 c2s_s  = uintBitsToFloat(cb3[3].xy), c2s_o  = uintBitsToFloat(cb3[3].zw);\n"
    " vec2 s2v    = uintBitsToFloat(cb3[4].xy);\n"
    " vec2 gfc = (gl_FragCoord.xy - rscale[0].zw) / rscale[0].xy;\n"
    " vec2 uv  = gfc * c2uv_s + c2uv_o;\n"
    " ivec2 dsz = textureSize(t0, 0), nsz = textureSize(t1, 0);\n"
    " ivec2 dip = clamp(ivec2(floor(uv * vec2(dsz))), ivec2(0), dsz - 1);\n"
    " ivec2 nip = clamp(ivec2(floor(uv * vec2(nsz))), ivec2(0), nsz - 1);\n"
    " float z = abs(texelFetch(t0, dip, 0).r);\n"
    " vec4 nt = texelFetch(t1, nip, 0);\n"
    " c1 = vec4(1.0, 0.0, 0.0, 1.0);\n"
    " c2 = vec4(nt.bbb, 1.0);\n"
    " if (z <= 1e-4 || z > 10000.0) { c0 = vec4(1.0, 0.0, 0.0, 1.0); return; }\n"
    " vec2 nxy = nt.rg * 2.0 - 1.0;\n"
    " float nz = (nt.a < 0.5 ? -1.0 : 1.0) * sqrt(max(1.0 - dot(nxy, nxy), 0.0));\n"
    " vec3 N = normalize(vec3(nxy, nz));\n"
    " vec3 P = gtao_vpos(uv, z, c2uv_s, c2uv_o, c2s_s, c2s_o, s2v);\n"
    " vec3 V = normalize(-P);\n"
    " float world_r = max(uintBitsToFloat(cb3[0].y), 0.35);\n"
    " float scr_r = clamp(abs(uintBitsToFloat(cb3[0].x) / z), 3.0, 120.0);\n"
    " vec2 uv_r = scr_r * abs(c2uv_s);\n"
    " float ign = fract(52.9829189 * fract(dot(floor(gl_FragCoord.xy), vec2(0.06711056, 0.00583715))));\n"
    " float jit = fract(ign * 7.319 + 0.17);\n"
    " float vis = 0.0;\n"
    " const int SLICES = 3, STEPS = 4;\n"
    " for (int sl = 0; sl < SLICES; sl++) {\n"
    "  float phi = (float(sl) + ign) * (3.14159265 / float(SLICES));\n"
    "  vec2 omega = vec2(cos(phi), sin(phi));\n"
    "  vec3 dir_v = vec3(omega.x, -omega.y, 0.0);\n"
    "  vec3 ortho = dir_v - dot(dir_v, V) * V;\n"
    "  vec3 axis  = normalize(cross(dir_v, V));\n"
    "  vec3 proj_n = N - axis * dot(N, axis);\n"
    "  float pn_len = length(proj_n);\n"
    "  float cos_n = clamp(dot(proj_n, V) / max(pn_len, 1e-5), -1.0, 1.0);\n"
    "  float n_ang = (dot(ortho, proj_n) >= 0.0 ? 1.0 : -1.0) * acos(cos_n);\n"
    "  float h1 = -1.0, h2 = -1.0;\n"
    "  for (int st = 0; st < STEPS; st++) {\n"
    "   float t = (float(st) + 0.25 + 0.5 * jit) / float(STEPS);\n"
    "   t *= t;\n"
    "   vec2 duv = omega * uv_r * max(t, 1.5 / max(scr_r, 1.5));\n"
    "   vec2 u1 = uv + duv;\n"
    "   if (all(greaterThanEqual(u1, vec2(0.0))) && all(lessThanEqual(u1, vec2(1.0)))) {\n"
    "    float zs = abs(texelFetch(t0, clamp(ivec2(floor(u1 * vec2(dsz))), ivec2(0), dsz - 1), 0).r);\n"
    "    if (zs > 1e-4 && zs < 10000.0) {\n"
    "     vec3 D = gtao_vpos(u1, zs, c2uv_s, c2uv_o, c2s_s, c2s_o, s2v) - P;\n"
    "     float d = length(D);\n"
    "     if (d > 1e-4 && d < world_r) {\n"
    "      float w = clamp((world_r - d) / (world_r * 0.45), 0.0, 1.0);\n"
    "      h1 = max(h1, mix(-1.0, dot(D, V) / d, w));\n"
    "     }\n"
    "    }\n"
    "   }\n"
    "   vec2 u2 = uv - duv;\n"
    "   if (all(greaterThanEqual(u2, vec2(0.0))) && all(lessThanEqual(u2, vec2(1.0)))) {\n"
    "    float zs = abs(texelFetch(t0, clamp(ivec2(floor(u2 * vec2(dsz))), ivec2(0), dsz - 1), 0).r);\n"
    "    if (zs > 1e-4 && zs < 10000.0) {\n"
    "     vec3 D = gtao_vpos(u2, zs, c2uv_s, c2uv_o, c2s_s, c2s_o, s2v) - P;\n"
    "     float d = length(D);\n"
    "     if (d > 1e-4 && d < world_r) {\n"
    "      float w = clamp((world_r - d) / (world_r * 0.45), 0.0, 1.0);\n"
    "      h2 = max(h2, mix(-1.0, dot(D, V) / d, w));\n"
    "     }\n"
    "    }\n"
    "   }\n"
    "  }\n"
    "  float a1 = n_ang + max(-acos(clamp(h2, -1.0, 1.0)) - n_ang, -1.5707963);\n"
    "  float a2 = n_ang + min( acos(clamp(h1, -1.0, 1.0)) - n_ang,  1.5707963);\n"
    "  float sin_n = sin(n_ang);\n"
    "  float v1 = -cos(2.0 * a1 - n_ang) + cos_n + 2.0 * a1 * sin_n;\n"
    "  float v2 = -cos(2.0 * a2 - n_ang) + cos_n + 2.0 * a2 * sin_n;\n"
    "  vis += pn_len * 0.25 * (v1 + v2);\n"
    " }\n"
    " float ao = clamp(vis / float(SLICES), 0.0, 1.0);\n"
    " c0 = vec4(ao, 0.0, 0.0, 1.0);\n"
    "}\n";

// Pass 2H (SLCT 86 H, hash f38cdb37598b7198): 7-tap physical-res depth-aware bilateral blur (horizontal).
static const char monado_gtao_blur_h_glsl[] =
    "#version 460\n"
    "layout(std140, set=1, binding=18) uniform RScale { vec4 rscale[129]; };\n"
    "layout(set=1, binding=34) uniform sampler2D t2;\n"  // gTDepth
    "layout(set=1, binding=35) uniform sampler2D t3;\n"  // gTSource (gTAO)
    "layout(location=0) out vec4 c0;\n"
    "void main() {\n"
    " ivec2 asz = textureSize(t3, 0), dsz = textureSize(t2, 0);\n"
    " ivec2 aip = clamp(ivec2(floor(gl_FragCoord.xy - rscale[0].zw)), ivec2(0), asz - 1);\n"
    " vec2 uv = (vec2(aip) + 0.5) / vec2(asz);\n"
    " float zc = abs(texelFetch(t2, clamp(ivec2(floor(uv * vec2(dsz))), ivec2(0), dsz - 1), 0).r);\n"
    " float ac = texelFetch(t3, aip, 0).r;\n"
    " if (zc <= 1e-4 || zc > 10000.0) { c0 = vec4(1.0, 0.0, 0.0, 1.0); return; }\n"
    " const float gw[4] = float[4](1.0, 0.85, 0.55, 0.25);\n"
    " float inv_sig = 1.0 / (zc * 0.015 + 0.005);\n"
    " float sum = ac, wsum = 1.0;\n"
    " for (int i = -3; i <= 3; i++) {\n"
    "  if (i == 0) continue;\n"
    "  ivec2 tip = clamp(aip + ivec2(i, 0), ivec2(0), asz - 1);\n"
    "  vec2 tuv = (vec2(tip) + 0.5) / vec2(asz);\n"
    "  float zi = abs(texelFetch(t2, clamp(ivec2(floor(tuv * vec2(dsz))), ivec2(0), dsz - 1), 0).r);\n"
    "  float w = gw[abs(i)] * exp(-abs(zi - zc) * inv_sig);\n"
    "  sum += texelFetch(t3, tip, 0).r * w;\n"
    "  wsum += w;\n"
    " }\n"
    " c0 = vec4(sum / wsum, 0.0, 0.0, 1.0);\n"
    "}\n";

