// Pass 4 (SLCT 88, hash c840dee21051ce2f): composite with the game's exact gTEtc material mask at physical UV.
static const char monado_gtao_composite_glsl[] =
    "#version 460\n"
    "layout(std140, set=1, binding=3) uniform CB3 { uvec4 cb3[16]; };\n"
    "layout(std140, set=1, binding=18) uniform RScale { vec4 rscale[129]; };\n"
    "layout(set=1, binding=32) uniform sampler2D t0;\n"  // gTEtc
    "layout(set=1, binding=33) uniform sampler2D t1;\n"  // gTAO
    "layout(location=0) out vec4 c0;\n"
    "void main() {\n"
    " ivec2 esz = textureSize(t0, 0);\n"
    " vec2 pfc = gl_FragCoord.xy - rscale[0].zw;\n"
    " ivec2 eip = clamp(ivec2(floor(pfc)), ivec2(0), esz - 1);\n"
    " float etc_a = texelFetch(t0, eip, 0).a;\n"
    " uint m = uint(clamp(trunc(etc_a * 255.0 + 0.000392), 0.0, 255.0));\n"
    " float out_ao = 1.0;\n"
    " if ((m & 7u) != 2u && (m & 0x80u) == 0u) {\n"
    "  vec2 uv = pfc / vec2(esz);\n"
    "  float ao = texture(t1, uv).r;\n"
    "  float k0 = uintBitsToFloat(cb3[1].x);\n"
    "  float wk = ((m & 0x20u) != 0u) ? uintBitsToFloat(cb3[1].z) : 1.0;\n"
    "  float str = wk * uintBitsToFloat(cb3[1].w);\n"
    "  float s = ao * k0 - k0 + 1.0;\n"
    "  out_ao = s * str - str + 1.0;\n"
    " }\n"
    " c0 = vec4(out_ao);\n"
    "}\n";
