#pragma once

// Build one conservative mesh bound per position binding in the preamble,
// then test its corners per instance and compact each draw bucket.
// Keep color commands in guest order. Only the depth list is sorted.
static const char draw_cull_glsl[] =
    "#version 460\n"
    "layout(local_size_x=64) in;\n"
    "struct Draw { uint indexCount, instanceCount, firstIndex; int vertexOffset; uint firstInstance; };\n"
    "layout(std430,set=0,binding=0) readonly buffer Jobs { uvec4 attr[4]; uvec4 args; Draw jobs[]; };\n"
    "layout(std430,set=0,binding=1) readonly buffer Geometry { uint words[]; };\n"
    "layout(std430,set=0,binding=2) readonly buffer View { uint camera[]; };\n"
    "layout(std430,set=0,binding=3) buffer Results { uint visible[256]; uint depth[256]; uint count; Draw lists[512]; uint materialPadding[63]; uint materialSlots[256]; };\n"
    "layout(std430,set=0,binding=4) buffer MeshBounds { uint bounds_words[8]; };\n"
    "layout(push_constant) uniform Push { uint phase; };\n"
    "shared uint planes, nearest;\n"
    "shared uint keep[256], keys[256], visible_count;\n"
    "shared vec3 tile_minimum[64], tile_maximum[64];\n"
    "bool fetch_attr(uint slot, uint vertex, uint instance, out vec4 v) {\n"
    "  uvec4 a=attr[slot]; uint bytes=a.w&31u; uint element=(a.w&32u)!=0u ? instance : vertex;\n"
    "  if (a.z<bytes || (a.y!=0u && element>(a.z-bytes)/a.y)) return false;\n"
    "  uint at=(a.x+element*a.y)>>2;\n"
    "  if (bytes==8u && (a.w&64u)!=0u) v=vec4(unpackHalf2x16(words[at]),unpackHalf2x16(words[at+1u]));\n"
    "  else if (bytes==8u) v=vec4(unpackSnorm2x16(words[at]),unpackSnorm2x16(words[at+1u]));\n"
    "  else { v=uintBitsToFloat(uvec4(words[at],words[at+1u],words[at+2u],0x3f800000u));\n"
    "         if(bytes==16u) v.w=uintBitsToFloat(words[at+3u]); }\n"
    "  return !any(isnan(v)) && !any(isinf(v));\n"
    "}\n"
    "float dot4(vec4 a,vec4 b) { return fma(a.w,b.w,fma(a.z,b.z,fma(a.y,b.y,a.x*b.x))); }\n"
    "vec4 matrix_row(uint row) { uint at=args.z+4u*row;\n"
    "  return uintBitsToFloat(uvec4(camera[at],camera[at+1u],camera[at+2u],camera[at+3u])); }\n"
    "uint order_float(float v) {\n"
    "  uint bits=floatBitsToUint(v);\n"
    "  return (bits&0x80000000u)!=0u ? ~bits : (bits^0x80000000u);\n"
    "}\n"
    "float decode_float(uint key) {\n"
    "  return uintBitsToFloat((key&0x80000000u)!=0u ? (key^0x80000000u) : ~key);\n"
    "}\n"
    "void build_bounds(uint lane) {\n"
    "  uint vertex=gl_GlobalInvocationID.x;\n"
    "  vec4 position=vec4(0,0,0,1);\n"
    "  if (vertex<args.y && !fetch_attr(0,vertex,0u,position)) {\n"
    "    atomicOr(bounds_words[6],1u);\n"
    "    position=vec4(0,0,0,1);\n"
    "  }\n"
    "  // Include the zero position returned by robust vertex input for invalid indices.\n"
    "  tile_minimum[lane]=min(vec3(0),position.xyz);\n"
    "  tile_maximum[lane]=max(vec3(0),position.xyz);\n"
    "  barrier();\n"
    "  for (uint span=32u;span>0u;span>>=1u) {\n"
    "    if (lane<span) {\n"
    "      tile_minimum[lane]=min(tile_minimum[lane],tile_minimum[lane+span]);\n"
    "      tile_maximum[lane]=max(tile_maximum[lane],tile_maximum[lane+span]);\n"
    "    }\n"
    "    barrier();\n"
    "  }\n"
    "  if (lane==0u) for (uint c=0u;c<3u;c++) {\n"
    "    atomicMax(bounds_words[c],~order_float(tile_minimum[0][c]));\n"
    "    atomicMax(bounds_words[3u+c],order_float(tile_maximum[0][c]));\n"
    "  }\n"
    "}\n"
    "void classify_corner(vec4 p,vec4 r0,vec4 r1,vec4 r2,vec3 magnitude,inout uint mask,inout uint nearKey) {\n"
    "  vec3 world=vec3(dot4(p,r0),dot4(p,r1),dot4(p,r2));\n"
    "  vec3 e=magnitude*2e-6;\n"
    "  vec4 clip,error;\n"
    "  for (uint c=0u;c<4u;c++) {\n"
    "    vec4 row=matrix_row(c);\n"
    "    clip[c]=fma(world.z,row.z,fma(world.y,row.y,world.x*row.x))+row.w;\n"
    "    error[c]=2e-6*dot(vec4(magnitude,1),abs(row))+dot(abs(row.xyz),e)+1e-5;\n"
    "  }\n"
    "  if ((args.w&1u)!=0u) { clip.z=(clip.z+clip.w)*0.5; error.z+=error.w; }\n"
    "  if (any(isnan(clip)) || any(isinf(clip)) || any(isnan(error)) || any(isinf(error))) { mask=0u; return; }\n"
    "  vec4 limit=vec4(clip.w)+error.w+error;\n"
    "  uint outside=(clip.x < -limit.x ? 1u:0u) | (clip.x > limit.x ? 2u:0u) |\n"
    "               (clip.y < -limit.y ? 4u:0u) | (clip.y > limit.y ? 8u:0u) |\n"
    "               (clip.z < -error.z ? 16u:0u) | (clip.z > limit.z ? 32u:0u);\n"
    "  mask &= outside;\n"
    "  float z=clip.w>0.0 ? clamp(clip.z/clip.w,0.0,1.0) : 0.0;\n"
    "  if ((args.w&2u)!=0u) z=1.0-z;\n"
    "  nearKey=min(nearKey,floatBitsToUint(z));\n"
    "}\n"
    "void test_draw_bounds(uint i,uint lane) {\n"
    "  if (lane==0u) { planes=63u; nearest=0x3f800000u; }\n"
    "  barrier();\n"
    "  Draw d=jobs[i];\n"
    "  uint mask=bounds_words[6]==0u ? 63u : 0u, key=0x3f800000u;\n"
    "  vec3 lo,hi;\n"
    "  for (uint c=0u;c<3u;c++) {\n"
    "    lo[c]=decode_float(~bounds_words[c]);\n"
    "    hi[c]=decode_float(bounds_words[3u+c]);\n"
    "  }\n"
    "  vec4 abs_position=vec4(max(abs(lo),abs(hi)),1);\n"
    "  for (uint n=lane;n<8u*d.instanceCount && mask!=0u;n+=64u) {\n"
    "    uint instance=d.firstInstance+n/8u;\n"
    "    vec4 r0,r1,r2;\n"
    "    if (instance<d.firstInstance || !fetch_attr(1,0u,instance,r0) ||\n"
    "        !fetch_attr(2,0u,instance,r1) || !fetch_attr(3,0u,instance,r2)) { mask=0u; break; }\n"
    "    vec3 corner=mix(lo,hi,bvec3((n&1u)!=0u,(n&2u)!=0u,(n&4u)!=0u));\n"
    "    vec3 magnitude=vec3(dot(abs_position,abs(r0)),dot(abs_position,abs(r1)),dot(abs_position,abs(r2)));\n"
    "    classify_corner(vec4(corner,1),r0,r1,r2,magnitude,mask,key);\n"
    "  }\n"
    "  atomicAnd(planes,mask); atomicMin(nearest,key); barrier();\n"
    "  if (lane==0u) { visible[i]=planes==0u ? 1u:0u; depth[i]=nearest; }\n"
    "}\n"
    "void compact_draws(uint lane) {\n"
    "  for(uint i=lane;i<args.x;i+=64u) { keep[i]=visible[i]; keys[i]=depth[i]; }\n"
    "  barrier();\n"
    "  if(lane==0) { uint total=0u; for(uint j=0;j<args.x;j++) total+=keep[j]; count=total; visible_count=total; }\n"
    "  barrier();\n"
    "  for(uint i=lane;i<args.x;i+=64u) {\n"
    "    if(i>=visible_count) {\n"
    "      Draw empty_draw=Draw(0u,0u,0u,0,0u); lists[i]=empty_draw; lists[256u+i]=empty_draw;\n"
    "    }\n"
    "    if(keep[i]==0u) continue;\n"
    "    uint ordered=0u, front=0u;\n"
    "    for(uint j=0;j<args.x;j++) if(keep[j]!=0u) {\n"
    "      ordered+=uint(j<i); front+=uint(keys[j]<keys[i] || (keys[j]==keys[i] && j<i));\n"
    "    }\n"
    "    lists[ordered]=jobs[i]; lists[256u+front]=jobs[i];\n"
    "    if((args.w&4u)!=0u) materialSlots[ordered]=i;\n"
    "  }\n"
    "}\n"
    "void main() {\n"
    "  uint lane=gl_LocalInvocationIndex;\n"
    "  if (phase==0u) build_bounds(lane);\n"
    "  else if (phase==1u) test_draw_bounds(gl_WorkGroupID.x,lane);\n"
    "  else compact_draws(lane);\n"
    "}\n";
